/**
 * 构建时根据 Vite env 生成 public/config.js，供 callback.html / logout.html 与 Vue 共用。
 * 开发时每次请求前也会刷新，避免手写 hostname 分支。
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

export function oidcConfigPlugin(env, options = {}) {
  const {
    configKey = "IAM_CLIENT_CONFIG",
    outFile = "public/config.js"
  } = options;

  function writeConfig() {
    const isLocalHostHint = (env.VITE_OIDC_ISSUER || "").includes("localhost");
    const body = `/** Auto-generated by vite oidcConfigPlugin — do not edit by hand */
(function () {
  var isLocalHost =
    location.hostname === "localhost" || location.hostname === "127.0.0.1";
  var cookieSuffix = isLocalHost ? "-" + (location.port || "80") : "";
  window.IAM_APP_COOKIE_KEYS = {
    token: "authorized-token" + cookieSuffix,
    multipleTabs: "multiple-tabs" + cookieSuffix
  };
  window.${configKey} = {
    iamBaseUrl: ${JSON.stringify(env.VITE_IAM_BASE_URL || "http://localhost:3000")},
    oidcIssuer: ${JSON.stringify(env.VITE_OIDC_ISSUER || "http://localhost:3000/oidc")},
    clientId: ${JSON.stringify(env.VITE_OIDC_CLIENT_ID || "")},
    scopes: ${JSON.stringify(env.VITE_OIDC_SCOPES || "openid profile email")},
    appCode: ${JSON.stringify(env.VITE_APP_CODE || "")}
  };
  // local hint: ${isLocalHostHint ? "localhost" : "remote"}
})();
`;
    const target = resolve(process.cwd(), outFile);
    mkdirSync(resolve(process.cwd(), "public"), { recursive: true });
    writeFileSync(target, body, "utf8");
  }

  return {
    name: "oidc-config-plugin",
    configResolved() {
      writeConfig();
    },
    configureServer() {
      writeConfig();
    },
    buildStart() {
      writeConfig();
    }
  };
}
